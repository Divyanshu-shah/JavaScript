let str = "Hello, World!";

console.log(str.toUpperCase()); // toUpperCase converts the string to uppercase

console.log(str.toLowerCase()); // toLowerCase converts the string to lowercase

console.log(str.indexOf("o")); // indexOf returns the index of the first occurrence of the specified value

console.log(str.lastIndexOf("o")); // lastIndexOf returns the index of the last occurrence of the specified value

console.log(str.startsWith("H")); // startsWith checks if the string starts with the specified value and returns true or false

console.log(str.endsWith("d")); // endsWith checks if the string ends with the specified value and returns true or false

console.log(str.includes("W")); // includes checks if the string contains the specified value and returns true or false

console.log(str.slice(1, 9)); // slice extracts a section of the string and returns it as a new string

console.log(str.substring(1, 9)); // substring returns the part of the string between the start and end indexes

